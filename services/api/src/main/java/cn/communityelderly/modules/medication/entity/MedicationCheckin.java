package cn.communityelderly.modules.medication.entity;

import com.baomidou.mybatisplus.annotation.IdType;
import com.baomidou.mybatisplus.annotation.TableId;
import com.baomidou.mybatisplus.annotation.TableName;

import java.time.LocalDateTime;

@TableName("medication_checkin")
public class MedicationCheckin {

    @TableId(value = "checkin_id", type = IdType.AUTO)
    private Long checkinId;

    private Long taskId;
    private Long elderId;
    private LocalDateTime checkinTime;
    private String checkinMode; // SELF_CONFIRMED, VOICE_CONFIRMED
    private String actualStatus; // TAKEN
    private String idempotencyKey;

    public Long getCheckinId() {
        return checkinId;
    }

    public void setCheckinId(Long checkinId) {
        this.checkinId = checkinId;
    }

    public Long getTaskId() {
        return taskId;
    }

    public void setTaskId(Long taskId) {
        this.taskId = taskId;
    }

    public Long getElderId() {
        return elderId;
    }

    public void setElderId(Long elderId) {
        this.elderId = elderId;
    }

    public LocalDateTime getCheckinTime() {
        return checkinTime;
    }

    public void setCheckinTime(LocalDateTime checkinTime) {
        this.checkinTime = checkinTime;
    }

    public String getCheckinMode() {
        return checkinMode;
    }

    public void setCheckinMode(String checkinMode) {
        this.checkinMode = checkinMode;
    }

    public String getActualStatus() {
        return actualStatus;
    }

    public void setActualStatus(String actualStatus) {
        this.actualStatus = actualStatus;
    }

    public String getIdempotencyKey() {
        return idempotencyKey;
    }

    public void setIdempotencyKey(String idempotencyKey) {
        this.idempotencyKey = idempotencyKey;
    }
}
